export type TranslationKey = keyof typeof messageRows;
export type TranslationValues = Readonly<Record<string, string | number>>;
export function translate(
  locale: AppLocale,
  key: TranslationKey,
  values: TranslationValues = {},
): string {
  const row = messageRows[key];
  const pattern = row?.[LOCALES.indexOf(locale)] || row?.[0] || key;
  return pattern.replace(/\{(\w+)\}/g, (match, name: string) =>
    values[name] === undefined ? match : String(values[name]),
  );
}
/** Explicit fallback for supplied navigation labels, never a DOM-wide translator. */
export function translateText(locale: AppLocale, text: string): string {
  return Object.prototype.hasOwnProperty.call(messageRows, text)
    ? translate(locale, text as TranslationKey)
    : text;
}
